"""Cookie formatting utilities for yt-dlp compatibility."""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from playwright.async_api import Cookie


def _sanitize_cookie_value(value: str) -> str:
    """Strip CR/LF characters from cookie values to prevent CRLF injection.

    Mirrors the sanitization already applied in
    :func:`vkdownloader.services.extractor._format_cookies_for_ffmpeg`.
    Cookie values containing ``\\r`` or ``\\n`` can inject additional lines
    into the Netscape cookie file, which downstream tools (yt-dlp) parse line
    by line.
    """
    return value.replace("\r", "").replace("\n", "")


def _normalize_expiry(value: float | int | None) -> int:
    """Map a cookie expiry to the Netscape-sentinel range.

    A browser session cookie is not an expired cookie. Playwright represents a
    session cookie with an expiry of ``-1`` (D-02), which the Netscape format
    rejects as a pre-epoch timestamp and the consumer (yt-dlp's
    ``YoutubeDLCookieJar``) silently drops at parse time. Map any missing,
    ``None``, or non-positive expiry to ``0`` — the Netscape sentinel for a
    "session cookie" — and pass positive timestamps through unchanged.
    """
    if value is None:
        return 0
    numeric = int(value)
    return numeric if numeric > 0 else 0


def _cookies_to_netscape(cookies_input: str | list[Cookie]) -> str:
    """Convert cookies to Netscape HTTP Cookie File format for yt-dlp.

    Accepts either a pre-formatted cookies string or a list of Cookie objects.
    When given Cookie objects, preserves the actual domain attribute.

    Args:
        cookies_input: Either a cookies string in format "name1=value1; name2=value2"
            or a list of Playwright Cookie objects.

    Returns:
        Netscape HTTP Cookie File format string.
    """
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by vkdownloader",
        "",
    ]

    # Handle empty input
    if not cookies_input:
        return "\n".join(lines)

    # Handle Cookie objects list (dict-like TypedDict)
    if isinstance(cookies_input, list):
        for cookie_item in cookies_input:
            name = _sanitize_cookie_value(cookie_item["name"])
            value = _sanitize_cookie_value(cookie_item["value"])
            domain = _sanitize_cookie_value(cookie_item.get("domain", ".vkvideo.ru"))
            path = _sanitize_cookie_value(cookie_item.get("path", "/"))
            secure = "TRUE" if cookie_item.get("secure", False) else "FALSE"
            # D-02: A browser session cookie is not an expired cookie. Playwright
            # represents a session cookie with an expiry of -1, which the Netscape
            # format cannot express. Normalise every missing / None / non-positive
            # expiry to 0 (the Netscape "session cookie" sentinel); positive
            # timestamps are preserved unchanged.
            expires = _normalize_expiry(cookie_item.get("expires", 0))

            if name and value:
                lines.append(f"{domain}\tTRUE\t{path}\t{secure}\t{expires}\t{name}\t{value}")
        return "\n".join(lines)

    # Handle string format (backward compatible)
    for cookie_part in cookies_input.split("; "):
        if "=" in cookie_part:
            name, value = cookie_part.split("=", 1)
            name = _sanitize_cookie_value(name)
            value = _sanitize_cookie_value(value)
            lines.append(f".vkvideo.ru\tTRUE\t/\tFALSE\t0\t{name}\t{value}")
    return "\n".join(lines)


__all__ = ["_cookies_to_netscape", "_sanitize_cookie_value"]
