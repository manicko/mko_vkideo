"""Cookie formatting utilities for yt-dlp compatibility."""

from __future__ import annotations

import ipaddress
from typing import TYPE_CHECKING
from urllib.parse import urlsplit

if TYPE_CHECKING:
    from playwright.async_api import Cookie


def _sanitize_cookie_value(value: str) -> str:
    return value.replace("\r", "").replace("\n", "")


def _normalize_expiry(value: float | int | None) -> int:
    if value is None:
        return 0
    numeric = int(value)
    return numeric if numeric > 0 else 0


def _cookies_to_netscape(cookies_input: str | list[Cookie]) -> str:
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by vkdownloader",
        "",
    ]
    if not cookies_input:
        return "\n".join(lines)
    if isinstance(cookies_input, list):
        for cookie_item in cookies_input:
            name = _sanitize_cookie_value(cookie_item["name"])
            value = _sanitize_cookie_value(cookie_item["value"])
            domain = _sanitize_cookie_value(cookie_item.get("domain", ".vkvideo.ru"))
            path = _sanitize_cookie_value(cookie_item.get("path", "/"))
            secure = "TRUE" if cookie_item.get("secure", False) else "FALSE"
            include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
            expires = _normalize_expiry(cookie_item.get("expires", 0))
            if name and value:
                lines.append(
                    f"{domain}\t{include_subdomains}\t{path}\t{secure}\t{expires}\t{name}\t{value}"
                )
        return "\n".join(lines)
    for cookie_part in cookies_input.split("; "):
        if "=" in cookie_part:
            name, value = cookie_part.split("=", 1)
            name = _sanitize_cookie_value(name)
            value = _sanitize_cookie_value(value)
            lines.append(f".vkvideo.ru\tTRUE\t/\tFALSE\t0\t{name}\t{value}")
    return "\n".join(lines)


def _cookie_get(cookie: object, key: str, default: object = None) -> object:
    if isinstance(cookie, dict):
        return cookie.get(key, default)
    return getattr(cookie, key, default)


def _is_ip_host(host: str) -> bool:
    try:
        ipaddress.ip_address(host)
        return True
    except ValueError:
        return False


def _host_matches(cookie_domain: str, host: str) -> bool:
    if not cookie_domain or not host:
        return False
    domain = cookie_domain.strip().lower()
    host = host.strip().lower()
    if _is_ip_host(host) or _is_ip_host(domain.lstrip(".")):
        return domain.lstrip(".") == host
    if domain.startswith("."):
        suffix = domain[1:]
        if host == suffix:
            return True
        return host.endswith(domain) and len(host) > len(domain)
    return domain == host


def _path_matches(cookie_path: str, request_path: str) -> bool:
    if not cookie_path:
        cookie_path = "/"
    if not request_path:
        request_path = "/"
    if request_path.startswith(cookie_path):
        if cookie_path.endswith("/"):
            return True
        if len(request_path) == len(cookie_path):
            return True
        if request_path[len(cookie_path) :].startswith("/"):
            return True
    return False


def scope_cookies_for_url(cookies: object, url: object) -> object:
    """Scope cookies to ``url`` per RFC 6265 host/path/scheme rules."""
    if cookies is None:
        return None
    if isinstance(cookies, str):
        return cookies
    if not isinstance(cookies, list):
        return cookies

    try:
        parsed = urlsplit(str(url))
    except Exception:  # noqa: BLE001
        return []
    host = parsed.hostname
    if not host:
        return []
    scheme = (parsed.scheme or "").lower()
    path = parsed.path or "/"

    result: list[object] = []
    for cookie in cookies:
        try:
            domain_attr = _cookie_get(cookie, "domain")
            cookie_path = _cookie_get(cookie, "path", "/")
            secure = bool(_cookie_get(cookie, "secure", False))
            if secure and scheme != "https":
                continue
            if domain_attr is None or str(domain_attr).strip() == "":
                domain_match = True
            else:
                domain_match = _host_matches(str(domain_attr), host)
            if not domain_match:
                continue
            if not _path_matches(str(cookie_path or "/"), path):
                continue
            result.append(cookie)
        except Exception:  # noqa: BLE001
            continue
    return result


__all__ = ["_cookies_to_netscape", "_sanitize_cookie_value", "scope_cookies_for_url"]
