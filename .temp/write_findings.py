# SEC-003
add("### SEC-003: Log file created with default umask, not owner-only permissions")
add()
add("| Field | Value |")
add("|-------|-------|")
add("| **ID** | SEC-003 |")
add("| **Severity** | LOW |")
add("| **Type** | BEST-PRACTICE |")
add("| **Affected Modules** | `src/vkdownloader/config.py` (`setup_logging`, lines 228-236) |")
add("| **Classification** | advisory |")
add()
add("**Description:** When `VKDOWNLOADER_LOG_FILE` is set, `setup_logging()` creates the log file")
add("via `logging.FileHandler(settings.log_file)` with no explicit file mode. `FileHandler` opens")
add("the file with `open(path, \"a\")` under the process umask, which on typical POSIX systems")
add("(umask `0o022`) yields mode `0o644` -- world- and group-readable. The application already")
add("demonstrates awareness of restrictive file modes for credential files (`services/cookies.py:72`")
add("uses `os.open(..., 0o600)`; `downloader.py:87` relies on `tempfile.mkstemp`'s `0o600`), but")
add("applies no equivalent protection to log files.")
add()
add("The log file may contain data that is not fully redacted: signed m3u8 URLs captured in")
add("unsanitized subprocess error output (SEC-002), exception tracebacks, and the cookie file")
add("temp path. A world-readable log file in a shared directory would expose these to other")
add("local users.")
add()
add("Verified at runtime: `logging.FileHandler` creates files with the raw umask -- in this")
add("environment (umask `0o000`) the resulting stat mode was `0o666` (world-readable/writable).")
add("On a standard Linux umask of `0o022` the result would be `0o644` (world-readable).")
add()
add("**Evidence:**")
add("- `src/vkdownloader/config.py:228-236`:")
add("  ```python")
add("  logging.basicConfig(")
add("      format=\"%(message)s\",")
add("      level=settings.log_level.value,")
add("      handlers=[")
add("          logging.StreamHandler()")
add("          if not settings.log_file")
add("          else logging.FileHandler(settings.log_file)   # no mode= => uses umask")
add("      ],")
add("  )")
add("  ```")
add("- The `log_file` field (`config.py:107-110`) goes through `expand_tilde_paths` (which")
add("  `.resolve()`s) but does NOT pass through `validate_output_path`, so there is no path")
add("  containment check on where the log file is written.")
add()
add("**Impact:** If a user sets `VKDOWNLOADER_LOG_FILE` to a path in a shared directory (or a")
add("container mounts a shared volume), and any subprocess error output containing signed URLs")
add("leaks into the log (SEC-002), the log file is readable by other users.")
add()
add("**Recommendation:** Create the log file with explicit `0o600` permissions before passing it")
add("to `FileHandler` (e.g. `fd = os.open(str(log_file), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600);")
add("handler = logging.FileHandler(os.fdopen(fd, \"a\"))`), or subclass `FileHandler` to enforce")
add("owner-only mode. Effort: trivial. Priority: recommended.")
add()
add("---")
